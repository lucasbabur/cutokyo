#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const schemaUrl = new URL("../schemas/settings/settings-patch.v1.json", import.meta.url);
const outputUrl = new URL("../ui/src/generated/settings.ts", import.meta.url);

function typeFor(definition, name) {
  const types = Array.isArray(definition.type) ? definition.type : [definition.type];
  const rendered = types.map((type) => {
    if (type === "boolean") return "boolean";
    if (type === "integer" || type === "number") return "number";
    if (type === "string") return "string";
    if (type === "null") return "null";
    throw new Error(`Unsupported settings schema type for ${name}: ${type}`);
  });
  return rendered.join(" | ");
}

function generate(schema) {
  if (schema.$schema !== "https://json-schema.org/draft/2020-12/schema") {
    throw new Error("Settings schema must use JSON Schema 2020-12");
  }
  if (schema.additionalProperties !== false || !schema.$id) {
    throw new Error("Settings schema must have a stable ID and reject unknown fields");
  }
  const fields = Object.entries(schema.properties ?? {}).map(
    ([name, definition]) => `  readonly ${name}?: ${typeFor(definition, name)};`,
  );
  return `// Generated by tools/generate-settings-types.mjs. Do not edit.\n` +
    `export const SETTINGS_PATCH_SCHEMA_ID =\n  ${JSON.stringify(schema.$id)};\n\n` +
    `/** Omission-preserving settings mutation. Missing fields remain unchanged. */\n` +
    `export interface SettingsPatch {\n${fields.join("\n")}\n}\n`;
}

const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
const generated = generate(schema);
if (process.argv.includes("--check")) {
  let current;
  try {
    current = await readFile(outputUrl, "utf8");
  } catch {
    console.error(`Missing generated settings type: ${fileURLToPath(outputUrl)}`);
    process.exitCode = 1;
  }
  if (current !== undefined && current !== generated) {
    console.error("Generated settings type is stale; run pnpm --dir ui generate:settings");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, generated, "utf8");
}
