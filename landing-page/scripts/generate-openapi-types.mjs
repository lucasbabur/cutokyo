import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

const outputPath = path.resolve("src/generated/fastapi/schema.ts");
const localExportPath = path.resolve("../back-end/openapi/openapi.json");
const source =
  process.env.FASTAPI_OPENAPI_SOURCE ??
  (existsSync(localExportPath)
    ? localExportPath
    : (process.env.NEXT_PUBLIC_FASTAPI_OPENAPI_URL ?? "http://localhost:8000/openapi.json"));
const openapiSource =
  existsSync(source) && source.endsWith(".json")
    ? JSON.parse(await readFile(source, "utf8"))
    : source;

const generatedSchemaAst = await openapiTS(openapiSource, {
  alphabetize: true,
});
const generatedSchema = astToString(generatedSchemaAst);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  [
    "/* eslint-disable */",
    "/* prettier-ignore */",
    "// This file is generated by `bun run openapi:generate`. Do not edit by hand.",
    "",
    generatedSchema,
  ].join("\n"),
  "utf8",
);

console.log(`Generated ${outputPath} from ${source}.`);
